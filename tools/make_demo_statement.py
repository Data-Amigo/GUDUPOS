"""Build a clearly labelled DEMO statement PDF from today's M-Pesa sales, to show the
statement check before the client sends a real till statement.

It is NOT an M-Pesa statement: the PDF says so at the top. It only copies the table
layout the statement reader expects, so the reconciliation can be demonstrated:

- every M-Pesa sale already paid in the demo appears with its (simulated) receipt -> Matched
- every waiting M-Pesa sale gets a payment a few minutes later, except the latest one
  -> Matched automatically, and the latest one shows as "sale with no payment"
- one extra payment (KSh 320 or another amount no sale has) with no sale -> "paid but no sale recorded"
- a withdrawal and its charge, which the reader must ignore

Usage (from the project folder, with the server's database):
    python tools/make_demo_statement.py                 # newest business; writes demo_statement.pdf, password 1234
    python tools/make_demo_statement.py --business gudu # pick the business by name
    python tools/make_demo_statement.py --password 5678 --out my_demo.pdf
"""
from __future__ import annotations

import argparse
import random
import string
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.pdfencrypt import StandardEncryption
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

NAIROBI = timedelta(hours=3)
HEADER = ["Receipt No.", "Completion Time", "Details", "Transaction Status", "Paid In", "Withdrawn", "Balance"]


def receipt() -> str:
    return "T" + "".join(random.choices(string.ascii_uppercase + string.digits, k=9))


def build_pdf(rows: list[dict], path: str, password: str | None) -> None:
    """rows: dicts with receipt, time (datetime, Nairobi), details, status, paid_in, withdrawn."""
    rows = sorted(rows, key=lambda r: r["time"])
    balance = 5000.0
    data = [HEADER]
    for r in rows:
        balance += r.get("paid_in", 0) - r.get("withdrawn", 0)
        data.append([r["receipt"], r["time"].strftime("%Y-%m-%d %H:%M:%S"), r["details"], r.get("status", "Completed"),
                     f"{r.get('paid_in', 0):,.2f}" if r.get("paid_in") else "",
                     f"-{r.get('withdrawn', 0):,.2f}" if r.get("withdrawn") else "", f"{balance:,.2f}"])
    enc = StandardEncryption(password, canPrint=1) if password else None
    doc = SimpleDocTemplate(path, pagesize=landscape(A4), encrypt=enc, title="DEMO statement")
    st = getSampleStyleSheet()
    table = Table(data, colWidths=[90, 120, 260, 95, 70, 70, 80], repeatRows=1)
    table.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.5, colors.grey), ("FONTSIZE", (0, 0), (-1, -1), 8),
                               ("BACKGROUND", (0, 0), (-1, 0), colors.lightgrey)]))
    doc.build([Paragraph("DEMO SAMPLE - NOT A REAL M-PESA STATEMENT", st["Title"]),
               Paragraph("Generated by the Gudu Bites POS prototype to demonstrate statement reconciliation.", st["Normal"]),
               Spacer(1, 10), table])


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default="gudu_pos.db")
    ap.add_argument("--out", default="demo_statement.pdf")
    ap.add_argument("--password", default="1234")
    ap.add_argument("--business", default="", help="part of the business name (default: the newest business)")
    args = ap.parse_args()

    import os
    os.environ.setdefault("DATABASE_URL", f"sqlite:///{Path(args.db).resolve()}")
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
    from sqlalchemy import select

    from app.db import SessionLocal
    from app.main import day_bounds
    from app.models import Business, Sale

    start, end, _ = day_bounds(None)
    with SessionLocal() as db:
        q = select(Business).order_by(Business.id.desc())
        if args.business:
            q = q.where(Business.name.ilike(f"%{args.business}%"))
        biz = db.scalars(q).first()
        if not biz:
            sys.exit("No business found. Sign up in the app first.")
        sales = db.scalars(select(Sale).where(Sale.business_id == biz.id, Sale.payment_method == "mpesa", Sale.status != "void",
                                              Sale.created_at >= start, Sale.created_at < end)
                           .order_by(Sale.created_at)).all()
        waiting = [s for s in sales if s.status == "awaiting_payment"]
        rows = []
        for s in sales:
            if s.payment:
                rows.append({"receipt": s.payment.trans_id, "time": s.payment.received_at + NAIROBI,
                             "details": f"Merchant Payment from {s.payment.msisdn} - {s.payment.payer_name}",
                             "paid_in": s.payment.amount})
            elif s is not (waiting[-1] if waiting else None):
                rows.append({"receipt": receipt(), "time": s.created_at + NAIROBI + timedelta(minutes=2),
                             "details": "Merchant Payment from 2547****318 - MARY WANJIRU", "paid_in": s.total})
    now = datetime.now(timezone.utc).replace(tzinfo=None) + NAIROBI
    extra = 320  # an amount no sale has, so it clearly shows as "paid but no sale recorded"
    while extra in {s.total for s in sales}:
        extra += 15
    rows.append({"receipt": receipt(), "time": now - timedelta(minutes=40),
                 "details": "Merchant Payment from 2547****902 - PAUL OTIENO", "paid_in": extra})
    w = receipt()
    rows.append({"receipt": w, "time": now - timedelta(minutes=30), "details": "Business Withdrawal to bank",
                 "withdrawn": 2000})
    rows.append({"receipt": w, "time": now - timedelta(minutes=30), "details": "Withdrawal Charge", "withdrawn": 30})
    build_pdf(rows, args.out, args.password)
    print(f"Wrote {args.out} for {biz.name} ({len(rows)} rows, password {args.password}) from {len(sales)} M-Pesa sales today")


if __name__ == "__main__":
    main()
